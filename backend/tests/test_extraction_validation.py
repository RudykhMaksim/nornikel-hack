"""Валидация точности извлечения на реальных предложениях из корпуса.

Методология: отобрано ~33 реальных предложения, содержащих распознаваемую
единицу измерения (mg/l, %, A/m2, C), из 6 реальных исходных документов
(Методы очистки шахтных вод.docx, Обзор технических решений..., Обеднение_
шлаков.docx, Медный купорос.pdf, Медные порошки.pdf, ТИ-5-2017...pdf),
для каждого запущен extract_numeric_constraints, результат вручную
сверен с исходным текстом.

Это выявило и исправило две настоящие ошибки точности (закреплены ниже
как регрессионные тесты) и два пробела в полноте (тоже исправлены):
"магнитным" совпадало с ключевым словом "магний" по голой подстроке;
"°С" с кириллической С (в отличие от латинской C) -- которые реальные
документы смешивают непоследовательно, судя по всему из-за копипаста --
вообще не распознавалось как единица температуры, незаметно теряя половину
диапазонных выражений вроде "от 2 °С до 8 °C". Ключевые слова для избыточной
щёлочности и голого содержания меди отсутствовали полностью (пробелы в
полноте, а не некорректный вывод).

Результат на отобранном наборе: 33 предложения, 14 содержали извлекаемое
ограничение после исправлений; все 14 значений/диапазонов/единиц оказались
верны; 6 из 14 получили конкретную метку параметра, остальные корректно
вернули parameter=None (нет уверенного совпадения по ключевому слову)
вместо угадывания -- по замыслу, неверная догадка хуже честного
"не определено" согласно требованию ТЗ "ошибки в извлечении концентраций
или температур недопустимы".
"""
from app import nlp


def test_real_sentence_solids_content_range():
    s = ("хвостохранилища, вмещающие пульпу с содержанием твердого 25-45% "
         "– это крупнейшие стоки воды горно-обогатительных предприятий")
    c = nlp.extract_numeric_constraints(s)
    assert c == [{"parameter": None, "operator": "range", "value": 25.0, "value2": 45.0, "unit": "%"}]


def test_real_sentence_sulfate_removal_limit():
    s = "В типичном случае можно удалить 1500-2500 мг/л сульфата."
    c = nlp.extract_numeric_constraints(s)
    assert c == [{"parameter": "sulfate_concentration", "operator": "range", "value": 1500.0, "value2": 2500.0, "unit": "mg/l"}]


def test_real_sentence_current_density():
    s = "Плотность тока 200-240 А/м2 представляет компромисс между скоростью осаждения и качеством осадка."
    c = nlp.extract_numeric_constraints(s)
    assert c == [{"parameter": "current_density", "operator": "range", "value": 200.0, "value2": 240.0, "unit": "A/m2"}]


def test_real_sentence_temperature_range_mixed_cyrillic_latin_c():
    """Регрессионный тест для настоящей ошибки, найденной при валидации на
    корпусе: реальные документы смешивают кириллическую С и латинскую C
    после "°" (судя по всему из-за копипаста); до исправления
    кириллическая-С половина диапазона незаметно пропадала."""
    s = "насыщенного раствора варьируется от 2 °С до 8 °C."
    c = nlp.extract_numeric_constraints(s)
    ops = {(x["operator"], x["value"]) for x in c}
    assert ops == {(">=", 2.0), ("<=", 8.0)}
    assert all(x["unit"] == "°C" for x in c)


def test_real_sentence_magnesium_false_positive_regression():
    """Регрессионный тест для настоящей ошибки, найденной при валидации на
    корпусе: "магнитным" (магнитная сепарация) совпадало с ключевым словом
    "магний" по голой подстроке ("магни" -- общий префикс)."""
    s = ("немагнитные частица «белого матта» после дробления отделяются "
         "магнитным способом, оставляя 5-6,5% Cu в шлаке")
    c = nlp.extract_numeric_constraints(s)
    assert len(c) == 1
    assert c[0]["parameter"] != "magnesium_concentration"
    assert c[0]["value"] == 5.0 and c[0]["value2"] == 6.5


def test_real_sentence_excess_alkalinity_keyword():
    s = ("процесс HDS генерирует мало избыточной щелочности (50-100 мг/л как CaCO3) "
         "даже при больших дозировках извести")
    c = nlp.extract_numeric_constraints(s)
    assert c == [{"parameter": "excess_alkalinity", "operator": "range", "value": 50.0, "value2": 100.0, "unit": "mg/l"}]


def test_real_sentence_bare_copper_content():
    s = "уровне 1,0 в раствор переходит 82-84% меди."
    c = nlp.extract_numeric_constraints(s)
    assert c == [{"parameter": "copper_concentration", "operator": "range", "value": 82.0, "value2": 84.0, "unit": "%"}]


def test_real_sentence_ambiguous_percentage_returns_none_not_a_guess():
    """82-84% было бы неоднозначным без "меди" поблизости -- проверяет, что
    экстрактор сообщает parameter=None, а не угадывает, если рядом нет
    ключевого слова (неверная метка хуже честной неопределённости)."""
    s = "По состоянию дел на 2020 г уровень потребления воды должен повыситься до 75%."
    c = nlp.extract_numeric_constraints(s)
    assert len(c) == 1
    assert c[0]["parameter"] is None
